// Replaces every <span data-mark> placeholder on the page with the mark.
export function mountMarks(root = document) {
  for (const el of root.querySelectorAll('[data-mark]')) {
    const svg = createMark({
      draw: el.dataset.mark === 'draw',
      small: el.dataset.size !== 'large',
      label: el.dataset.label || '',
    });
    for (const cls of el.classList) svg.classList.add(cls);
    el.replaceWith(svg);
  }
}
