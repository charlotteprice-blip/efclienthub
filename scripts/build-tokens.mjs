// Builds the app's tokens from the Executive Frame brand pack.
//
//   brand/ef-tokens.json    the pack's tokens, copied in unchanged. The single
//                           source for colour, radius, spacing, motion and
//                           the mark. Replace this file when the pack changes.
//   brand/app-tokens.json   what the app adds: its own type sizes (the pack's
//                           scale is for the website), control sizes, and the
//                           1 value where the apps do not follow the pack yet.
//
// It writes 3 files, none of which is edited by hand:
//   brand/tokens.json         the joined tokens the contrast check reads
//   public/css/tokens.css     the CSS variables, under the names the app uses
//   public/js/mark-paths.js   the mark's loop and triangle for the inline mark
//
//   node scripts/build-tokens.mjs        (npm run tokens)

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

const root = join(dirname(new URL(import.meta.url).pathname), '..');
const read = (p) => JSON.parse(readFileSync(join(root, p), 'utf8'));
const pack = read('brand/ef-tokens.json');
const app = read('brand/app-tokens.json');

const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const px = (n) => `${n}px`;

// ---------- join ----------

const palette = Object.fromEntries(Object.entries(pack.palette).map(([k, v]) => [k, v.hex]));
const themes = {
  light: { ...pack.themes.light, ...(app.primaryOverride?.light ?? {}), error: pack.application.error.light },
  inverted: { ...pack.themes.inverted, ...(app.primaryOverride?.inverted ?? {}), error: pack.application.error.dark },
};
const application = Object.fromEntries(['error', 'success', 'warning', 'info'].map((k) => [k, { text: pack.application[k].light, tint: pack.application[k].tint, onNavy: pack.application[k].dark }]));

const tokens = {
  _note: `Generated by scripts/build-tokens.mjs from brand/ef-tokens.json (Executive Frame brand pack ${pack.version}, ${pack.date}) and brand/app-tokens.json. Do not edit by hand.`,
  packVersion: pack.version,
  palette,
  themes,
  application,
  font: { family: pack.type.family, weights: pack.type.weights, fallback: app.fontFallback },
  type: app.type,
  spacing: pack.spacing,
  radius: pack.radius,
  sizes: app.sizes,
  motion: { durationMs: pack.motion.durationMs, easing: pack.motion.easing, markDrawOnMs: pack.motion.markDrawOnMs },
  mark: { loop: pack.logo.mark.loop.path, triangle: pack.logo.mark.triangle, strokes: pack.logo.mark.strokes, minimum: pack.logo.minimum, clearSpace: pack.logo.clearSpace },
};
writeFileSync(join(root, 'brand/tokens.json'), `${JSON.stringify(tokens, null, 2)}\n`);

// ---------- tokens.css ----------

const t = tokens;
const lines = [];
const out = (s = '') => lines.push(s);
const themeBlock = (theme) => Object.entries(theme).map(([k, v]) => `  --${kebab(k)}: ${v};`).join('\n');
const LATIN = 'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD';
const LATIN_EXT = 'U+0100-02BA, U+02BD-02C5, U+02C7-02CC, U+02CE-02D7, U+02DD-02FF, U+0304, U+0308, U+0329, U+1D00-1DBF, U+1E00-1E9F, U+1EF2-1EFF, U+2020, U+20A0-20AB, U+20AD-20C0, U+2113, U+2C60-2C7F, U+A720-A7FF';

out(`/* Executive Frame app tokens. Generated by scripts/build-tokens.mjs from`);
out(`   brand/ef-tokens.json (brand pack ${pack.version}, ${pack.date}) and`);
out('   brand/app-tokens.json. Do not edit by hand. */');
out();
for (const [subset, range] of [['latin', LATIN], ['latin-ext', LATIN_EXT]]) {
  for (const w of t.font.weights) out(`@font-face { font-family: "${t.font.family}"; font-style: normal; font-display: swap; font-weight: ${w}; src: url("/assets/fonts/figtree-${subset}-${w}-normal.woff2") format("woff2"); unicode-range: ${range}; }`);
}
out();
out(':root {');
out('  /* palette */');
for (const [k, v] of Object.entries(t.palette)) out(`  --ef-${kebab(k)}: ${v};`);
out();
out('  /* light theme (default). primary is navy: the pack still says slate and');
out('     the designer is changing it to navy (brand/app-tokens.json). */');
out(themeBlock(t.themes.light));
out();
out('  /* inverted theme values, for reference by components */');
for (const [k, v] of Object.entries(t.themes.inverted)) out(`  --inv-${kebab(k)}: ${v};`);
out();
out('  /* application colours: interfaces only, never brand surfaces. Each is');
out('     text and icon on its own tint, always with an icon and a word. */');
for (const [k, v] of Object.entries(t.application)) {
  out(`  --app-${k}: ${v.text};`);
  out(`  --app-${k}-tint: ${v.tint};`);
}
out();
out('  /* font */');
out(`  --font-family: "${t.font.family}", system-ui, -apple-system, "Segoe UI", Roboto, sans-serif;`);
out();
out('  /* type: size / line height / weight / tracking (the app\'s own sizes) */');
for (const [name, s] of Object.entries(t.type)) {
  const n = kebab(name);
  out(`  --type-${n}-size: ${px(s.size)};`);
  out(`  --type-${n}-line: ${px(s.lineHeight)};`);
  out(`  --type-${n}-weight: ${s.weight};`);
  out(`  --type-${n}-tracking: ${s.tracking}em;`);
}
out();
out('  /* spacing */');
t.spacing.forEach((v, i) => out(`  --space-${i + 1}: ${px(v)};`));
out();
out('  /* radius. Surfaces are flat: no shadows. */');
for (const [k, v] of Object.entries(t.radius)) out(`  --radius-${kebab(k)}: ${px(v)};`);
out();
out('  /* sizes */');
for (const [k, v] of Object.entries(t.sizes)) out(`  --${kebab(k)}: ${k === 'iconStroke' ? v : px(v)};`);
out();
out('  /* motion */');
out(`  --motion-duration: ${t.motion.durationMs}ms;`);
out(`  --motion-easing: ${t.motion.easing};`);
out(`  --mark-draw-on: ${t.motion.markDrawOnMs}ms;`);
out('}');
out();
out('/* Inverted theme, used for calls to action and emphasis panels. */');
out('[data-theme="inverted"] {');
out(themeBlock(t.themes.inverted));
out('}');
out();
out('@media (prefers-reduced-motion: reduce) {');
out('  :root { --motion-duration: 0ms; --mark-draw-on: 0ms; }');
out('}');
writeFileSync(join(root, 'public/css/tokens.css'), `${lines.join('\n')}\n`);

// ---------- the mark ----------

writeFileSync(
  join(root, 'public/js/mark-paths.js'),
  `// The Executive Frame mark on its 100 unit grid. Generated by
// scripts/build-tokens.mjs from brand/ef-tokens.json (brand pack ${pack.version}).
// Do not edit by hand, and never redraw, close, rotate or flip the loop.

export const LOOP = '${t.mark.loop}';
export const TRIANGLE = '${t.mark.triangle}';
// Loop stroke widths: standard from 24 to 240px, display at 240px and above,
// favicon from 16 to 24px.
export const STROKES = ${JSON.stringify(t.mark.strokes)};
`,
);

console.log('Wrote brand/tokens.json, public/css/tokens.css and public/js/mark-paths.js');
